import math

def main():
    value = 16.7
    print("Math Library Functions Demo")
    print(f"sqrt({value}) = {math.sqrt(value):.4f}")
    print(f"pow(2, 5) = {math.pow(2, 5)}")
    print(f"factorial(7) = {math.factorial(7)}")
    print(f"ceil(4.2) = {math.ceil(4.2)}")
    print(f"floor(4.9) = {math.floor(4.9)}")
    print(f"sin(pi/2) = {math.sin(math.pi / 2):.4f}")
    print(f"cos(0) = {math.cos(0):.4f}")
    print(f"tan(pi/4) = {math.tan(math.pi / 4):.4f}")
    print(f"log(100) = {math.log(100):.4f}")
    print(f"exp(2) = {math.exp(2):.4f}")

if __name__ == "__main__":
    main()
